"""Offline tests of the relay's gateway-retry rules: the browser is replaced by a fake RSG."""

from __future__ import annotations

import json
import threading
import urllib.error
import urllib.request

import pytest

import relay

HTML_502 = (b"<html><head><title>ERROR: The request could not be satisfied</title></head>"
            b"<body><h1>502 Bad Gateway ERROR</h1><center>generated by 10.1.2.3 x.example.com</center></body></html>")


class FakeRsg:
    """Answers tools/call like the RSG; `fail[name]` makes the next call of that tool return a 502:
    "landed" (applied, then 502), "lost" (502, not applied) or True (502 for other tools)."""

    def __init__(self):
        self.sim_time = 0.0
        self.calls: list[str] = []
        self.fail: dict[str, object] = {}

    def _ok(self, rid, payload):
        return 200, {"ct": "application/json", "sid": None}, relay.synth_result(rid, payload)

    def _bad(self):
        return 502, {"ct": "text/html; charset=UTF-8", "sid": None}, HTML_502

    def __call__(self, method, headers, body):
        m = json.loads(body)
        if m.get("method") != "tools/call":
            self.calls.append(m["method"])
            if self.fail.pop(m["method"], None):
                return self._bad()
            return self._ok(m.get("id"), {"ok": True})
        name, args = m["params"]["name"], m["params"]["arguments"]
        self.calls.append(name)
        mode = self.fail.pop(name, None)
        if name == "simulation_advance":
            if mode == "lost":
                return self._bad()
            self.sim_time += 60
            return self._bad() if mode == "landed" else self._ok(m["id"], {"accepted": True})
        if name == "simulation_status":
            return self._ok(m["id"], {"test_id": args.get("test_id"), "status": "PAUSED", "sim_time": self.sim_time})
        if mode:
            return self._bad()
        return self._ok(m["id"], {"accepted": True})


@pytest.fixture
def rsg(monkeypatch):
    fake = FakeRsg()
    monkeypatch.setattr(relay, "browser_fetch", fake)
    monkeypatch.setattr(relay.time, "sleep", lambda s: None)
    srv = relay.ThreadingHTTPServer(("127.0.0.1", 0), relay.Handler)
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    fake.url = f"http://127.0.0.1:{srv.server_address[1]}/mcp"
    yield fake
    srv.shutdown()
    srv.server_close()


def post(url, payload):
    req = urllib.request.Request(url, data=json.dumps(payload).encode(), headers={"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req) as r:
            return r.status, r.read()
    except urllib.error.HTTPError as e:
        return e.code, e.read()


def call(url, name, args):
    return post(url, {"jsonrpc": "2.0", "id": 7, "method": "tools/call", "params": {"name": name, "arguments": args}})


def text_of(body: bytes) -> dict:
    return json.loads(json.loads(body)["result"]["content"][0]["text"])


def test_advance_that_landed_is_not_resent(rsg):
    rsg.fail["simulation_advance"] = "landed"
    status, body = call(rsg.url, "simulation_advance", {"test_id": "t-1", "run_for": "60s"})
    assert status == 200
    assert rsg.sim_time == 60  # applied exactly once
    assert rsg.calls == ["simulation_status", "simulation_advance", "simulation_status"]
    assert "relay_note" in text_of(body)


def test_advance_that_was_lost_is_resent_once(rsg):
    rsg.fail["simulation_advance"] = "lost"
    status, body = call(rsg.url, "simulation_advance", {"test_id": "t-1", "run_for": "60s"})
    assert status == 200
    assert rsg.sim_time == 60
    assert rsg.calls == ["simulation_status", "simulation_advance", "simulation_status", "simulation_advance"]
    assert "relay_note" not in text_of(body)


def test_absolute_command_is_retried(rsg):
    rsg.fail["simulation_command"] = True
    status, _ = call(rsg.url, "simulation_command", {"command_type": "tx_power", "params": {"cell": "c", "power": 40}})
    assert status == 200
    assert rsg.calls == ["simulation_command", "simulation_command"]


@pytest.mark.parametrize("method", ["initialize", "notifications/initialized", "tools/list"])
def test_session_calls_are_retried(rsg, method):
    rsg.fail[method] = True
    status, _ = post(rsg.url, {"jsonrpc": "2.0", "id": 1, "method": method, "params": {}})
    assert status == 200
    assert rsg.calls == [method, method]


def test_unknown_state_changing_call_is_passed_through(rsg):
    rsg.fail["scenario_save"] = True
    status, body = call(rsg.url, "scenario_save", {"name": "x", "config": {}})
    assert status == 502
    assert body == HTML_502
    assert rsg.calls == ["scenario_save"]


def test_get_is_405(rsg):
    req = urllib.request.Request(rsg.url, method="GET")
    with pytest.raises(urllib.error.HTTPError) as e:
        urllib.request.urlopen(req)
    assert e.value.code == 405


def test_error_page_summary_is_masked():
    s = relay.html_summary(HTML_502)
    assert "502 Bad Gateway" in s and "could not be satisfied" in s
    assert "10.1.2.3" not in s and "example.com" not in s


def test_rpc_label_never_includes_arguments():
    body = json.dumps({"method": "tools/call", "params": {"name": "simulation_command",
                                                          "arguments": {"test_id": "secret-ish"}}}).encode()
    assert relay.rpc_label(body) == "tools/call:simulation_command"
