import { ArrowDown, Bot, Gauge, Lock } from 'lucide-react'
import type { Rec } from '@/core/types'
import { Hash, Panel } from '@/ui'
import { fixed, pct, utc } from './format'
import { Banner, NoteChip, ProvenanceChip } from './shared'

// Consortium mode, from GET /api/twinview/consortium. Dataset facts come from silos/manifest.json (written by our
// generator: simulated operators on the same 4-cell Maveric twin, never partner data). Metrics come only from
// `t2.fl` result records; until one exists every metric says "not run yet". The laptop preview is labelled LOCAL.

const KINDS: [string, string, string][] = [
  ['zero', 'no change', 'var(--s4)'],
  ['single_power', 'power, one cell', 'var(--release)'],
  ['single_tilt', 'tilt, one cell', 'var(--learn)'],
  ['single_both', 'both, one cell', 'var(--verify)'],
  ['multi', 'several cells', 'var(--operate)'],
]

export function ConsortiumView({ data }: { data: Rec }) {
  const facts: Rec | null = data.facts
  const runs: Rec[] = data.runs ?? []
  return (
    <div className="flex flex-col gap-4">
      {facts && (
        <div className="mb-0 flex items-start gap-2 rounded-md border px-4 py-2.5 text-cap text-ink-1" role="status"
          style={{ borderColor: 'color-mix(in oklab, var(--warn) 55%, transparent)', background: 'color-mix(in oklab, var(--warn) 10%, transparent)' }}>
          <span><span className="font-medium">Simulated operators.</span> Each silo is generated by our own code from the same 4-cell Maveric twin: {facts.manifest?.label}. Dataset facts only; no data rows are shown.</span>
        </div>
      )}
      {runs.length > 0 && <Banner p={data.runs_provenance} />}
      {!facts && <div className="rounded-md border border-line p-4 text-cap text-ink-2">{data.facts_note}</div>}
      {facts && (
        <>
          <div className="grid grid-cols-1 gap-4 lg:grid-cols-3">
            {(facts.silos as Rec[]).map((s) => <SiloCard key={s.silo} s={s} />)}
          </div>
          <Hub hub={data.hub} />
        </>
      )}
      <MetricsPanel data={data} />
      {facts && <SharedTest facts={facts} />}
    </div>
  )
}

function ClusterGlyphs({ n }: { n: number }) {
  // one glyph per cluster: a 2x2 square of cells, the same 4-cell twin each time
  return (
    <div className="flex flex-wrap gap-1.5" aria-label={`${n} clusters of 4 cells`}>
      {Array.from({ length: n }, (_, i) => (
        <svg key={i} viewBox="0 0 20 20" className="size-6 shrink-0" aria-hidden>
          {[0, 1, 2, 3].map((c) => (
            <rect key={c} x={1 + (c % 2) * 9.5} y={1 + Math.floor(c / 2) * 9.5} width={8.5} height={8.5} rx={1.5}
              fill="color-mix(in oklab, var(--learn) 35%, transparent)" stroke="var(--learn)" strokeWidth={0.8} />
          ))}
        </svg>
      ))}
    </div>
  )
}

function MixBar({ mix }: { mix: Rec }) {
  const k: Rec = mix?.kinds ?? {}
  return (
    <div>
      <div className="flex h-2.5 w-full overflow-hidden rounded-sm" role="img"
        aria-label={KINDS.map(([key, label]) => `${label} ${pct(k[key])}`).join(', ')}>
        {KINDS.map(([key, label, color]) => (typeof k[key] === 'number' && k[key] > 0
          ? <span key={key} title={`${label}: ${pct(k[key])}`} style={{ width: `${k[key] * 100}%`, background: color }} />
          : null))}
      </div>
      <div className="mt-1 text-micro text-ink-3">
        {mix?.lean ?? 'change mix'} · power changed in <span className="tnum">{pct(mix?.power_change_fraction)}</span>, tilt in <span className="tnum">{pct(mix?.tilt_change_fraction)}</span> of steps
      </div>
    </div>
  )
}

function SiloCard({ s }: { s: Rec }) {
  const range = (r: unknown, unit: string) => (Array.isArray(r) && r.length === 2 ? `${fixed(r[0], 0)}–${fixed(r[1], 0)} ${unit}` : '—')
  return (
    <Panel id={`twin-silo-${s.silo}`} plane="learn" title={`Operator ${s.silo}`} subtitle={`${s.size ?? ''} · ${s.clusters} cluster${s.clusters === 1 ? '' : 's'}`}
      actions={<NoteChip label="GENERATED" title="Dataset facts from silos/manifest.json, written by our generator. Not partner data." />}>
      <ClusterGlyphs n={typeof s.clusters === 'number' ? s.clusters : 0} />
      <dl className="tnum mt-3 grid grid-cols-2 gap-x-3 gap-y-1 text-cap">
        <dt className="text-ink-3">cells</dt><dd className="mono text-ink-1">{s.cells ?? '—'}</dd>
        <dt className="text-ink-3">users per cluster</dt><dd className="mono text-ink-1">{s.users_per_cluster ?? '—'} {s.mobility ?? ''}</dd>
        <dt className="text-ink-3">start power</dt><dd className="mono text-ink-1">{range(s.power_start_dbm, 'dBm')}</dd>
        <dt className="text-ink-3">start tilt</dt><dd className="mono text-ink-1">{range(s.tilt_start_deg, '°')}</dd>
        <dt className="text-ink-3">noise floor</dt><dd className="mono text-ink-1">{fixed(s.noise_floor_dbm, 0)} dBm</dd>
        <dt className="text-ink-3">train rows</dt><dd className="mono text-ink-1">{s.train_rows?.toLocaleString?.() ?? '—'}</dd>
      </dl>
      <div className="mt-3"><MixBar mix={s.mix} /></div>
      <div className="mt-2 flex min-w-0 items-center gap-1 text-micro text-ink-3">train file <Hash value={s.train_sha256} /></div>
    </Panel>
  )
}

function Hub({ hub }: { hub: Rec }) {
  return (
    <div className="flex flex-col items-center gap-1.5 text-center" data-hub>
      <div className="flex flex-wrap justify-center gap-x-6 gap-y-1 text-micro text-ink-2">
        {['A', 'B', 'C'].map((s) => <span key={s} className="flex items-center gap-1"><ArrowDown size={12} aria-hidden />{s}: {hub?.carries}</span>)}
      </div>
      <div className="flex max-w-full items-center gap-2 rounded-lg border-2 px-4 py-2" style={{ borderColor: 'var(--learn)', background: 'color-mix(in oklab, var(--learn) 10%, var(--s1))' }}>
        <Lock size={16} aria-hidden style={{ color: 'var(--learn)' }} />
        <div className="min-w-0 text-left">
          <div className="text-body font-medium text-ink-1">Secure aggregation · {hub?.name}</div>
          <div className="text-micro text-ink-3">adds up masked updates; sees no silo’s weights or data on their own</div>
        </div>
      </div>
      <ArrowDown size={14} className="text-ink-3" aria-hidden />
      <div className="text-cap font-medium text-ink-1">One shared response model</div>
      <ArrowDown size={14} className="text-ink-3" aria-hidden />
      <div className="flex flex-wrap justify-center gap-2">
        <span className="flex items-center gap-1.5 rounded-md border border-line bg-s2 px-2.5 py-1 text-cap text-ink-1"><Bot size={14} aria-hidden /><span className="mono">ran___predict</span> (agents ask it)</span>
        <span className="flex items-center gap-1.5 rounded-md border border-line bg-s2 px-2.5 py-1 text-cap text-ink-1"><Gauge size={14} aria-hidden />trust gate (predicted vs measured)</span>
      </div>
    </div>
  )
}

function MetricsPanel({ data }: { data: Rec }) {
  const runs: Rec[] = data.runs ?? []
  const run = runs[0]
  const pv: Rec | null = data.preview
  return (
    <Panel id="twin-fl-metrics" plane="learn" title="Federated vs local-only" subtitle="skill on the one shared test set (lower is better)"
      actions={run ? <ProvenanceChip p={data.runs_provenance} /> : <NoteChip label="NOT RUN YET" title="No t2.fl result record exists yet" />}>
      <table className="w-full table-fixed text-cap" data-state={run ? 'run' : 'not-run'}>
        <thead>
          <tr className="text-left text-micro text-ink-3">
            <th className="py-1 pr-2 font-medium">Silo</th>
            <th className="px-1 py-1 text-right font-medium">Local only</th>
            <th className="px-1 py-1 text-right font-medium">Federated</th>
          </tr>
        </thead>
        <tbody>
          {['A', 'B', 'C'].map((s) => {
            const r: Rec | undefined = run?.per_silo?.[s]
            return (
              <tr key={s} className="border-t border-line/60">
                <td className="py-1 pr-2 text-ink-2">Operator {s}</td>
                <td className="tnum mono px-1 text-right text-ink-1">{r?.local_only_skill ?? (run ? '—' : 'not run yet')}</td>
                <td className="tnum mono px-1 text-right text-ink-1">{r?.federated_skill ?? (run ? '—' : 'not run yet')}</td>
              </tr>
            )
          })}
        </tbody>
      </table>
      <div className="mt-2 flex flex-wrap gap-x-4 gap-y-0.5 text-micro text-ink-3">
        <span>ε <span className="tnum mono">{run ? (run.dp?.enabled ? fixed(run.dp.epsilon, 2) : 'DP off') : 'not run yet'}</span></span>
        <span>final aggregation round <span className="tnum mono">{run?.final_round ?? 'not run yet'}</span></span>
        {run && <span>run <span className="mono">{run.run_id}</span> · {utc(run.time, true)}</span>}
        {run && run.same_test_set === false && <span style={{ color: 'var(--critical-ink)' }}>scored on a different test set than the manifest’s shared test</span>}
      </div>
      {pv && (
        <div className="mt-4 rounded-md border border-dashed p-3" data-preview="local" style={{ borderColor: 'color-mix(in oklab, var(--warn) 55%, transparent)' }}>
          <div className="flex flex-wrap items-center gap-2">
            <NoteChip label="LOCAL · SIMULATED" title={pv.note} />
            <span className="text-cap font-medium text-ink-1">Laptop preview: {pv.what}</span>
          </div>
          <table className="mt-2 w-full table-fixed text-cap">
            <thead>
              <tr className="text-left text-micro text-ink-3">
                <th className="py-1 pr-2 font-medium">Own test segment</th>
                <th className="px-1 py-1 text-right font-medium">Local only</th>
                <th className="px-1 py-1 text-right font-medium">Local FedAvg</th>
              </tr>
            </thead>
            <tbody>
              {(pv.rows as Rec[]).map((r) => (
                <tr key={r.silo} className="border-t border-line/60 text-ink-3">
                  <td className="py-1 pr-2">Operator {r.silo}</td>
                  <td className="tnum mono px-1 text-right">{r.local_only_skill ?? '—'}</td>
                  <td className="tnum mono px-1 text-right">{r.federated_skill ?? '—'}</td>
                </tr>
              ))}
            </tbody>
          </table>
          <p className="mt-1 text-micro text-ink-3">{pv.note} {pv.model ? `Model ${pv.model}, ${pv.seeds} seeds.` : ''}</p>
        </div>
      )}
    </Panel>
  )
}

function SharedTest({ facts }: { facts: Rec }) {
  const t: Rec = facts.shared_test ?? {}
  const m: Rec = facts.manifest ?? {}
  return (
    <Panel id="twin-shared-test" plane="verify" title="The one shared test set" subtitle={`${facts.split} split`}>
      <div className="flex flex-wrap gap-x-4 gap-y-1 text-cap text-ink-2">
        <span><span className="tnum mono text-ink-1">{t.rows?.toLocaleString?.() ?? '—'}</span> rows from <span className="tnum mono text-ink-1">{t.clusters ?? '—'}</span> held-out clusters</span>
        <span className="flex min-w-0 items-center gap-1">sha256 <Hash value={t.sha256} /></span>
        <span>segments <span className="mono break-all text-ink-1">{(t.segments ?? []).join(', ')}</span></span>
      </div>
      <div className="mt-1 flex flex-wrap gap-x-4 gap-y-0.5 text-micro text-ink-3">
        <span>manifest <span className="mono">{m.run_id}</span></span>
        <span className="flex items-center gap-1">config <Hash value={m.config_sha256} /></span>
        <span className="flex items-center gap-1">generator <Hash value={m.generator_commit} /></span>
        <span>{m.twin}</span>
      </div>
    </Panel>
  )
}
