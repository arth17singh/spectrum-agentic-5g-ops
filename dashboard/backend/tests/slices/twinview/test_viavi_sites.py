import json

from fastapi import FastAPI
from fastapi.testclient import TestClient

from spectrum.slices.twinview import router
from spectrum.slices.twinview.routes import viavi_sites_view

DOC = {"source": "test fixture", "read_at": "2026-11-03T07:00:00Z", "scenarios": [
    {"name": "Scenario A - Region 1", "cells": 6, "ues": 100,
     "sites": [{"name": "s1", "lat": 18.01, "lon": -66.61, "cells": 3}, {"name": "s2", "lat": None, "lon": None, "cells": 3}]},
    {"name": "bad", "sites": [{"name": "x", "lat": 999, "lon": 0, "cells": 1}]},
    {"name": "generated", "cells": 7, "sites": [], "note": "generated by the RSG", "map_center": {"lat": 53.35, "lon": -6.27}}]}


def test_view_keeps_documented_fields_and_drops_bad_coordinates():
    v = viavi_sites_view(DOC)
    assert v["scenarios"][0]["sites"][0] == {"name": "s1", "cells": 3.0, "lat": 18.01, "lon": -66.61}
    assert v["scenarios"][0]["sites"][1]["lat"] is None and v["scenarios"][1]["sites"][0]["lat"] is None
    assert v["scenarios"][2]["sites"] == [] and v["scenarios"][2]["map_center"] == {"lat": 53.35, "lon": -6.27}
    assert viavi_sites_view({"nope": 1}) is None


def test_route_reads_the_newest_extract_or_says_not_loaded(tmp_path, monkeypatch):
    monkeypatch.setenv("SPECTRUM_RECORDS_ROOT", str(tmp_path))
    app = FastAPI()
    app.include_router(router)
    c = TestClient(app)
    assert c.get("/api/twinview/viavi-sites").json() == {"loaded": False}
    for stamp, name in (("20261103T060000Z", "old"), ("20261103T070000Z", "Scenario A - Region 1")):
        p = tmp_path / "outputs" / "viavi-sites" / stamp / "viavi_sites.json"
        p.parent.mkdir(parents=True)
        p.write_text(json.dumps({**DOC, "scenarios": [{**DOC["scenarios"][0], "name": name}]}))
    d = c.get("/api/twinview/viavi-sites").json()
    assert d["loaded"] and d["extract"] == "20261103T070000Z" and d["scenarios"][0]["name"] == "Scenario A - Region 1"
