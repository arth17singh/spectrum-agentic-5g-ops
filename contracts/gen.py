"""Generate JSON Schema and TypeScript types from team13_contracts.

Writes, relative to the repo root:
  contracts/schema/<kind>.schema.json            one JSON Schema (draft 2020-12) per kind
  dashboard/frontend/src/contracts/records.gen.ts TypeScript interfaces + RecordKind union

The TypeScript is produced by walking the JSON Schema emitted here, so the two
always agree. Output is deterministic: running this twice gives identical files.

Usage:
  python contracts/gen.py                 # write into this repo
  python contracts/gen.py --check         # exit 1 if any generated file is stale
  python contracts/gen.py --out-root DIR  # write under DIR instead (tests)
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parent
sys.path.insert(0, str(HERE))

from team13_contracts.records import KINDS, RECORD_MODELS, SCHEMA_VERSION, Envelope  # noqa: E402

SCHEMA_DIALECT = "https://json-schema.org/draft/2020-12/schema"
SCHEMA_REL = Path("contracts/schema")
TS_REL = Path("dashboard/frontend/src/contracts/records.gen.ts")
HEADER = (
    "// GENERATED by contracts/gen.py from contracts/team13_contracts. DO NOT EDIT.\n"
    "// Regenerate: python contracts/gen.py   (the M1 gate checks git diff --exit-code)\n"
)


# --------------------------------------------------------------------------
# JSON Schema
# --------------------------------------------------------------------------


def kind_schema(kind: str) -> dict[str, Any]:
    schema = RECORD_MODELS[kind].model_json_schema(mode="validation")
    out = {
        "$schema": SCHEMA_DIALECT,
        "$id": f"https://team13.invalid/contracts/{kind}.schema.json",
        **schema,
    }
    return out


def dump_json(obj: Any) -> str:
    return json.dumps(obj, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


# --------------------------------------------------------------------------
# TypeScript (from the JSON Schema)
# --------------------------------------------------------------------------

JSON_VALUE_TS = (
    "export type JsonValue =\n"
    "  | string\n"
    "  | number\n"
    "  | boolean\n"
    "  | null\n"
    "  | JsonValue[]\n"
    "  | { [key: string]: JsonValue };\n"
)


def _ref_name(ref: str) -> str:
    prefix = "#/$defs/"
    if not ref.startswith(prefix):
        raise ValueError(f"unsupported $ref {ref}")
    return ref[len(prefix) :]


def ts_type(s: dict[str, Any]) -> str:
    if "$ref" in s:
        return _ref_name(s["$ref"])
    if "anyOf" in s:
        parts: list[str] = []
        for sub in s["anyOf"]:
            t = ts_type(sub)
            if t not in parts:
                parts.append(t)
        return " | ".join(parts)
    if "const" in s:
        return json.dumps(s["const"])
    if "enum" in s:
        return " | ".join(json.dumps(v) for v in s["enum"])
    t = s.get("type")
    if t == "string":
        return "string"
    if t in ("number", "integer"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        inner = ts_type(s.get("items", {}))
        return f"Array<{inner}>"
    if t == "object":
        if "properties" in s:
            raise ValueError("inline object with properties: give it a named model")
        ap = s.get("additionalProperties", True)
        if isinstance(ap, dict):
            return f"{{ [key: string]: {ts_type(ap)} }}"
        return "{ [key: string]: unknown }"
    if s == {}:
        return "unknown"
    raise ValueError(f"cannot map schema to TypeScript: {s}")


def _doc(text: str | None, indent: str) -> str:
    if not text:
        return ""
    text = " ".join(text.split()).replace("*/", "*\\/")
    return f"{indent}/** {text} */\n"


def ts_interface(name: str, s: dict[str, Any], extra_fields: str = "") -> str:
    required = set(s.get("required", []))
    lines = [_doc(s.get("description"), ""), f"export interface {name} {{\n"]
    lines.append(extra_fields)
    for prop, ps in s.get("properties", {}).items():
        opt = "" if prop in required else "?"
        lines.append(_doc(ps.get("description"), "  "))
        lines.append(f"  {prop}{opt}: {ts_type(ps)};\n")
    if s.get("additionalProperties") is True:
        lines.append("  /** v0: extra keys are allowed on this record. */\n")
        lines.append("  [key: string]: unknown;\n")
    lines.append("}\n")
    return "".join(lines)


def collect_defs(schemas: dict[str, dict[str, Any]]) -> dict[str, dict[str, Any]]:
    defs: dict[str, dict[str, Any]] = {}
    for kind, sch in schemas.items():
        for name, d in sch.get("$defs", {}).items():
            if name in defs and defs[name] != d:
                raise ValueError(f"$defs/{name} differs between kinds (seen again in {kind})")
            defs[name] = d
    return defs


def build_ts(schemas: dict[str, dict[str, Any]]) -> str:
    out: list[str] = [HEADER, "\n", JSON_VALUE_TS, "\n"]
    out.append(f"export const SCHEMA_VERSION = {json.dumps(SCHEMA_VERSION)} as const;\n\n")
    out.append("export const RECORD_KINDS = [\n")
    for k in KINDS:
        out.append(f"  {json.dumps(k)},\n")
    out.append("] as const;\n\n")
    out.append("export type RecordKind = (typeof RECORD_KINDS)[number];\n\n")

    defs = collect_defs(schemas)
    for name in sorted(defs):
        if name == "JsonValue":
            continue
        out.append(ts_interface(name, defs[name]))
        out.append("\n")

    env = Envelope.model_json_schema(mode="validation")
    out.append(
        ts_interface(
            "RecordEnvelope",
            env,
            extra_fields="  kind: RecordKind;\n",
        )
    )
    out.append("\n")

    names: list[str] = []
    for kind in KINDS:
        sch = schemas[kind]
        name = sch["title"]
        names.append(name)
        out.append(ts_interface(name, sch))
        out.append("\n")

    out.append("export type AnyRecord =\n")
    for n in names:
        out.append(f"  | {n}\n")
    out.append(";\n\n")
    out.append("export interface RecordByKind {\n")
    for kind, n in zip(KINDS, names):
        out.append(f"  {kind}: {n};\n")
    out.append("}\n")
    text = "".join(out)
    while "\n\n\n" in text:
        text = text.replace("\n\n\n", "\n\n")
    return text


# --------------------------------------------------------------------------
# Entry point
# --------------------------------------------------------------------------


def render() -> dict[Path, str]:
    schemas = {k: kind_schema(k) for k in KINDS}
    files: dict[Path, str] = {SCHEMA_REL / f"{k}.schema.json": dump_json(s) for k, s in schemas.items()}
    files[TS_REL] = build_ts(schemas)
    return files


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out-root", type=Path, default=REPO_ROOT)
    ap.add_argument("--check", action="store_true", help="compare only; exit 1 if anything is stale")
    args = ap.parse_args(argv)

    stale: list[str] = []
    for rel, text in render().items():
        path = args.out_root / rel
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if args.check:
            stale.append(str(rel))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {rel}")
    if stale:
        print("stale generated files (run python contracts/gen.py):\n  " + "\n  ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
